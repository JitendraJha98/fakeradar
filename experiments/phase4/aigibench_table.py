"""Write AIGIBENCH.md and the paper table from the AIGIBench evaluation report.

    python experiments/phase4/aigibench_table.py

Source: runs/lens_law/phase4-aigibench/aigibench_report.json, written by
experiments/phase4/jobs/eval_aigibench.py. Numbers are never typed by hand.
"""

from __future__ import annotations

import json
import statistics
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
REPORT = REPO / "runs" / "lens_law" / "phase4-aigibench" / "aigibench_report.json"
COLS = [
    ("fast_eq", "fast, equalized"),
    ("accurate_eq", "accurate, equalized"),
    ("fast_raw", "fast, as stored"),
    ("accurate_raw", "accurate, as stored"),
    ("commfor", "Community Forensics"),
]
PRETTY = {
    "FLUX1-dev": "FLUX.1-dev",
    "SD3": "SD 3",
    "Midjourney": "Midjourney v6",
    "DALLE-3": "DALL-E 3",
    "Imagen3": "Imagen 3",
    "SDXL": "SDXL",
    "CommunityAI": "CommunityAI (wild)",
    "SocialRF": "SocialRF (wild)",
}


def load() -> dict:
    subsets = json.loads(REPORT.read_text(encoding="utf-8"))["subsets"]
    return {k: v for k, v in subsets.items() if "error" not in v}


def markdown(subsets: dict) -> str:
    lines = [
        "# AIGIBench: fakeradar on 2024-25 generators",
        "",
        "Generated by `experiments/phase4/aigibench_table.py` from",
        "`runs/lens_law/phase4-aigibench/aigibench_report.json`; do not edit by hand.",
        "",
        "One bounded evaluation, nothing trained or tuned. AIGIBench test subsets",
        "(Li et al. 2025, `HorizonTEL/AIGIBench`, CC-BY-NC-SA-4.0); per subset a fixed",
        "sample of 500 real and 500 generated images (sorted by a hash of the path).",
        "fakeradar: published `fast-v0` and `accurate-v0` (trained on GenImage SD v1.4",
        "only, seed 42). Community Forensics: public weights, scored as stored; it was",
        "trained on thousands of generators and may have seen some of these.",
        "",
        "## AUROC",
        "",
        "| Test set | " + " | ".join(name for _, name in COLS) + " |",
        "|---|" + "---|" * len(COLS),
    ]
    for s, e in subsets.items():
        lines.append(
            f"| {PRETTY.get(s, s)} | " + " | ".join(f"{e[k]['auroc']:.4f}" for k, _ in COLS) + " |"
        )
    lines.append(
        "| **Mean** | "
        + " | ".join(
            f"**{statistics.mean(e[k]['auroc'] for e in subsets.values()):.4f}**" for k, _ in COLS
        )
        + " |"
    )
    lines += [
        "",
        "## TPR at 5% FPR",
        "",
        "| Test set | fast, equalized | accurate, equalized | Community Forensics |",
        "|---|---|---|---|",
    ]
    for s, e in subsets.items():
        lines.append(
            f"| {PRETTY.get(s, s)} | "
            + " | ".join(f"{e[k]['tpr@5%fpr']:.3f}" for k in ("fast_eq", "accurate_eq", "commfor"))
            + " |"
        )
    lines += [
        "",
        "## File formats in the sample",
        "",
        "| Test set | real | generated |",
        "|---|---|---|",
    ]
    for s, e in subsets.items():
        f = e["formats"]
        lines.append(f"| {PRETTY.get(s, s)} | {', '.join(f['0'])} | {', '.join(f['1'])} |")
    lines += [
        "",
        "Generated images are PNG in every subset while most real images are JPEG, so",
        "the as-stored columns can reward a compression shortcut; the equalized",
        "columns JPEG-encode every non-JPEG image once at quality 96, as in training.",
    ]
    return "\n".join(lines) + "\n"


def latex(subsets: dict) -> str:
    keys = ("fast_eq", "accurate_eq", "commfor")
    lines = [
        "% Generated by experiments/phase4/aigibench_table.py -- do not edit by hand.",
        "\\begin{table}[t]\\centering\\small",
        "\\caption{AUROC on AIGIBench 2024--25 generators and in-the-wild sets (500 real + 500 generated each). "
        "fakeradar trained on SD v1.4 only, compression equalized; Community Forensics re-evaluated as stored.}",
        "\\label{tab:aigibench}",
        "\\begin{tabular}{l c c c}\\hline",
        "Test set & fast & accurate & CommFor\\\\\\hline",
    ]
    for s, e in subsets.items():
        lines.append(
            f"{PRETTY.get(s, s)} & " + " & ".join(f"{e[k]['auroc']:.3f}" for k in keys) + "\\\\"
        )
    lines.append(
        "\\hline\\textbf{Mean} & "
        + " & ".join(
            f"{statistics.mean(e[k]['auroc'] for e in subsets.values()):.3f}" for k in keys
        )
        + "\\\\"
    )
    lines += ["\\hline\\end{tabular}", "\\end{table}"]
    return "\n".join(lines) + "\n"


def card_section(tier: str) -> str:
    """Model-card section for one fakeradar tier ("fast" or "accurate")."""
    if not REPORT.exists():
        return ""
    subsets = load()
    key = f"{tier}_eq"
    lines = [
        "",
        "## Newer generators (AIGIBench, 2024-25)",
        "",
        "One bounded evaluation, nothing retrained: a fixed sample of 500 real and 500",
        "generated images per AIGIBench test set (Li et al. 2025), compression equalized.",
        "Expect much lower accuracy than on GenImage: this model learned from one 2022",
        "generator. Community Forensics (public, trained on thousands of generators,",
        "possibly including some of these) is shown for reference.",
        "",
        "| Test set | AUROC, this model | AUROC, Community Forensics |",
        "|---|---|---|",
    ]
    for s, e in subsets.items():
        lines.append(
            f"| {PRETTY.get(s, s)} | {e[key]['auroc']:.4f} | {e['commfor']['auroc']:.4f} |"
        )
    mean = statistics.mean(e[key]["auroc"] for e in subsets.values())
    ref = statistics.mean(e["commfor"]["auroc"] for e in subsets.values())
    lines.append(f"| **Mean** | **{mean:.4f}** | {ref:.4f} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    subsets = load()
    (REPO / "experiments" / "phase4" / "AIGIBENCH.md").write_bytes(
        markdown(subsets).encode("utf-8")
    )
    (REPO / "paper" / "generated_tables_aigibench.tex").write_bytes(latex(subsets).encode("utf-8"))
    print(markdown(subsets))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
