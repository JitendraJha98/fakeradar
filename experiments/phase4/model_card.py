def card(root: Path = ROOT) -> str:
    results = summarize(root).split("\n", 1)[1]  # drop the page title
    results = results.replace(
        "Generated by `experiments/phase4/summarize.py`", "Generated from the run"
    )
    return HEADER + "## Measured results\n" + results + card_section("fast") + FOOTER


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_bytes(card().encode("utf-8"))
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
