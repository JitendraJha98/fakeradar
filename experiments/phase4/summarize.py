"""Build the results tables from the run folders, so no number is typed by hand.

    python experiments/phase4/summarize.py --out experiments/phase4/RESULTS.md

Reads benchmark_*.md and robustness_equalized.md of each run in
runs/lens_law/ and writes mean ± sample standard deviation over seeds.
"""

from __future__ import annotations

import argparse
import re
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2] / "runs" / "lens_law"
MAIN = {"42": "phase4-train-fast", "43": "phase4-seed43", "44": "phase4-seed44"}
ABLATION = {"42": "phase4-nocoh42", "43": "phase4-nocoh43"}
ACCURATE = {"42": "phase4-accurate42", "43": "phase4-accurate43", "44": "phase4-accurate44"}  # accurate tier: adds the frozen CLIP ViT-B branch
# Reference detector re-evaluated (not retrained) on the same test images: public
# Community Forensics weights, trained on thousands of generators.
BASELINE = {"commfor": "phase4-baseline-commfor"}
GENERATORS = (
    "stable_diffusion_v_1_4",
    "stable_diffusion_v_1_5",
    "wukong",
    "VQDM",
    "Midjourney",
    "glide",
    "BigGAN",
    "ADM",
)
CONDITIONS = ("clean", "jpeg90", "jpeg70", "jpeg50", "jpeg30", "down0.75", "down0.5", "blur1.0")
_ROW = re.compile(r"^\| ([^|]+?) \|(.*)$")


def read_table(path: Path) -> dict[str, list[str]]:
    """First column -> remaining cells, for a markdown table written by the harness."""
    rows = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        m = _ROW.match(line)
        if m and not set(m.group(1)) <= {"-"}:
            rows[m.group(1).strip()] = [c.strip() for c in m.group(2).split("|")[:-1]]
    return rows


def benchmark(path: Path) -> dict[str, dict[str, float]]:
    """generator -> {auroc, tpr5}; MEAN row -> {auroc}."""
    rows = read_table(path)
    out = {g: {"auroc": float(rows[g][1]), "tpr5": float(rows[g][4])} for g in GENERATORS}
    out["MEAN"] = {"auroc": float(rows["MEAN (8 gen)"][1])}
    return out


def robustness(path: Path) -> dict[str, float]:
    rows = read_table(path)
    return {c: float(rows[c][0]) for c in CONDITIONS}


def fmt(values: list[float]) -> str:
    if len(values) == 1:
        return f"{values[0]:.4f}"
    return f"{statistics.mean(values):.4f} ± {statistics.stdev(values):.4f}"


def available(runs: dict[str, str], root: Path) -> dict[str, Path]:
    return {s: root / d for s, d in runs.items() if (root / d / "benchmark_equalized.md").exists()}


def summarize(root: Path = ROOT) -> str:
    main, abl = available(MAIN, root), available(ABLATION, root)
    eq = {s: benchmark(p / "benchmark_equalized.md") for s, p in main.items()}
    raw = {s: benchmark(p / "benchmark_raw.md") for s, p in main.items()}
    ab = {s: benchmark(p / "benchmark_equalized.md") for s, p in abl.items()}
    rob = {s: robustness(p / "robustness_equalized.md") for s, p in main.items()}
    rob_ab = {s: robustness(p / "robustness_equalized.md") for s, p in abl.items()}
    acc = available(ACCURATE, root)
    acc_eq = {s: benchmark(p / "benchmark_equalized.md") for s, p in acc.items()}
    acc_rob = {s: robustness(p / "robustness_equalized.md") for s, p in acc.items()}

    def col(data, gen, key="auroc"):
        return [d[gen][key] for d in data.values()]

    lines = [
        "# fakeradar fast tier: measured results",
        "",
        "Generated by `experiments/phase4/summarize.py` from the run folders; do not edit by hand.",
        "",
        f"- Seeds: {', '.join(sorted(main))} (ablation: {', '.join(sorted(abl)) or 'none'}).",
        "  Values are mean ± sample standard deviation over seeds.",
        "- Training: GenImage Stable Diffusion v1.4 only, 95,000 images (5% more held out for",
        "  model selection and calibration), 5 epochs, one Kaggle T4, compression history",
        "  equalized (JPEG quality 96 once for non-JPEG images).",
        "- Test: GenImage `val` split, 1,000 generated images per generator against 2,000",
        "  pooled real images; robustness on 500 real + 500 generated test images.",
        "",
        "## Cross-generator AUROC",
        "",
        "| Generator | AUROC, equalized | TPR at 5% FPR, equalized | AUROC, as stored |",
        "|---|---|---|---|",
    ]
    for g in GENERATORS:
        lines.append(
            f"| {g} | {fmt(col(eq, g))} | {fmt(col(eq, g, 'tpr5'))} | {fmt(col(raw, g))} |"
        )
    lines.append(f"| **Mean of 8** | **{fmt(col(eq, 'MEAN'))}** | | {fmt(col(raw, 'MEAN'))} |")
    lines += [
        "",
        "## Robustness (AUROC, equalized)",
        "",
        "| Condition | With coherence | Without coherence (ablation) |",
        "|---|---|---|",
    ]
    for c in CONDITIONS:
        no = fmt([r[c] for r in rob_ab.values()]) if rob_ab else "–"
        lines.append(f"| {c} | {fmt([r[c] for r in rob.values()])} | {no} |")
    if ab:
        lines += [
            "",
            "## Coherence ablation (AUROC, equalized)",
            "",
            "| Generator | With coherence | Without coherence |",
            "|---|---|---|",
        ]
        for g in (*GENERATORS, "MEAN"):
            lines.append(f"| {g} | {fmt(col(eq, g))} | {fmt(col(ab, g))} |")
    base = available(BASELINE, root)
    if base:
        b_eq = [benchmark(p / "benchmark_equalized.md") for p in base.values()]
        b_raw = [benchmark(p / "benchmark_raw.md") for p in base.values()]
        b_rob = [robustness(p / "robustness_equalized.md") for p in base.values()]
        lines += [
            "",
            "## Reference: Community Forensics (re-evaluated, not retrained)",
            "",
            "Public weights `OwensLab/commfor-model-384`, trained on thousands of generators",
            "(very likely including GenImage's), scored on the same test images. Not a",
            "same-training-data comparison.",
            "",
            "| Generator / condition | fakeradar fast | Community Forensics |",
            "|---|---|---|",
        ]
        for g in (*GENERATORS, "MEAN"):
            lines.append(f"| {g} | {fmt(col(eq, g))} | {fmt([d[g]['auroc'] for d in b_eq])} |")
        lines.append(
            f"| MEAN, as stored | {fmt(col(raw, 'MEAN'))} | {fmt([d['MEAN']['auroc'] for d in b_raw])} |"
        )
        for c in CONDITIONS:
            lines.append(
                f"| robustness: {c} | {fmt([r[c] for r in rob.values()])} | "
                f"{fmt([r[c] for r in b_rob])} |"
            )
    if acc:
        seeds = ", ".join(sorted(acc))
        lines += [
            "",
            f"## Accurate tier (adds a frozen CLIP ViT-B branch; seed {seeds}, equalized)",
            "",
            "Same data, epochs and test sets as the fast tier.",
            "",
            "| Generator / condition | Fast tier | Accurate tier |",
            "|---|---|---|",
        ]
        for g in (*GENERATORS, "MEAN"):
            lines.append(f"| {g} | {fmt(col(eq, g))} | {fmt(col(acc_eq, g))} |")
        for c in CONDITIONS:
            lines.append(
                f"| robustness: {c} | {fmt([r[c] for r in rob.values()])} | "
                f"{fmt([r[c] for r in acc_rob.values()])} |"
            )
    return "\n".join(lines) + "\n"


REPO = ROOT.parents[1]
HF = "https://huggingface.co/JitendraJha98/fakeradar-fast"


def _replace_between(path: Path, tag: str, body: str) -> None:
    text = path.read_bytes().decode("utf-8")
    start, end = f"<!-- {tag}:start -->", f"<!-- {tag}:end -->"
    a, b = text.index(start) + len(start), text.index(end)
    nl = chr(10)
    path.write_bytes((text[:a] + nl + body.rstrip(nl) + nl + text[b:]).encode("utf-8"))


def docs_tables(root: Path = ROOT) -> tuple[str, str]:
    """(README table, leaderboard row), both from the run folders."""
    main = available(MAIN, root)
    eq = {s: benchmark(p / "benchmark_equalized.md") for s, p in main.items()}
    rob = {s: robustness(p / "robustness_equalized.md") for s, p in main.items()}
    n = len(main)
    rows = [
        f"fast-v0, trained on GenImage SD v1.4 only; AUROC, mean ± std over {n} seeds;",
        "compression history equalized. Full tables: [experiments/phase4/RESULTS.md]"
        "(experiments/phase4/RESULTS.md).",
        "",
        "| test generator | AUROC |",
        "|---|---|",
    ]
    rows += [f"| {g} | {fmt([d[g]['auroc'] for d in eq.values()])} |" for g in GENERATORS]
    rows.append(f"| **mean of 8** | **{fmt([d['MEAN']['auroc'] for d in eq.values()])}** |")
    board = [
        "| model | train data | mean AUROC (8 gen) | AUROC @ jpeg50 | weights |",
        "|---|---|---|---|---|",
        f"| fast-v0 | GenImage SD1.4, 95k images, 5 epochs | "
        f"{fmt([d['MEAN']['auroc'] for d in eq.values()])} | "
        f"{fmt([r['jpeg50'] for r in rob.values()])} | [HF]({HF}) (CC-BY-NC-SA-4.0) |",
    ]
    acc = available(ACCURATE, root)
    if acc:
        a_eq = [benchmark(p / "benchmark_equalized.md") for p in acc.values()]
        a_rob = [robustness(p / "robustness_equalized.md") for p in acc.values()]
        board.append(
            f"| accurate-v0 ({len(acc)} seed) | GenImage SD1.4, 95k images, 5 epochs | "
            f"{fmt([d['MEAN']['auroc'] for d in a_eq])} | {fmt([r['jpeg50'] for r in a_rob])} | "
            "not published |"
        )
    base = available(BASELINE, root)
    if base:
        c_eq = [benchmark(p / "benchmark_equalized.md") for p in base.values()]
        c_rob = [robustness(p / "robustness_equalized.md") for p in base.values()]
        board.append(
            "| Community Forensics (reference, re-evaluated) | thousands of generators | "
            f"{fmt([d['MEAN']['auroc'] for d in c_eq])} | {fmt([r['jpeg50'] for r in c_rob])} | "
            "[HF](https://huggingface.co/OwensLab/commfor-model-384) (MIT) |"
        )
    else:
        board.append("| accurate-v0 | GenImage SD1.4 | *not trained yet* | | |")
    return chr(10).join(rows), chr(10).join(board)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--out", type=Path, default=None)
    parser.add_argument("--update-docs", action="store_true", help="rewrite README/docs tables")
    args = parser.parse_args(argv)
    text = summarize(args.root)
    if args.update_docs:
        table, board = docs_tables(args.root)
        _replace_between(REPO / "README.md", "results", table)
        _replace_between(REPO / "docs" / "benchmarks.md", "leaderboard", board)
    if args.out:
        args.out.write_bytes(text.encode("utf-8"))
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
